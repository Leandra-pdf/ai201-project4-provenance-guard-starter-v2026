"""
Scoring module for combining detection signals and producing user-facing
classification results. Turning two numbers into one, and one number into something a person can read.

This module turns the numerical outputs of the model and stylometry
components into a single score, then translates that score into a
classification and an explanation that can be presented to the writer.

Two functions handle these responsibilities:

- combine_signals() combines the model signal and style signal using a
  weighted average. The model signal contributes 70% of the result, while
  the style signal contributes 30%. This keeps the trained detector as the
  primary signal while allowing writing characteristics to contribute
  supporting evidence.

- score_to_label() compares the combined score against the configured
  thresholds and returns a classification ("ai", "human", or "unsure")
  along with a plain-language explanation. This separates the numerical
  scoring logic from the messages presented to the writer.

The combined score is used downstream by the submission endpoint to
determine the result recorded in the audit log and returned to the writer.

These scores are estimates, not proof of authorship. In particular, the
combined score is not a calibrated probability that a piece of writing
was generated by AI.
"""

import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine the model and style signals into one score.
    Strong disagreement between the signals produces a neutral score.

    Args:
        model_score: from `detector.model_signal` — how predictable the text is.
        style_score: from `stylometry.style_signal` — the shape of the text.

    Returns:
        A float from 0.0 (confidently human) to 1.0 (confidently AI).

    """
    model_says_ai = model_score >= config.AI_THRESHOLD
    model_says_human = model_score <= config.HUMAN_THRESHOLD

    style_says_ai = style_score >= config.AI_THRESHOLD
    style_says_human = style_score <= config.HUMAN_THRESHOLD

    # If one signal strongly suggests AI and the other strongly
    # suggests human, return a neutral score.
    if (model_says_ai and style_says_human) or (
        model_says_human and style_says_ai
    ):
        return 0.50

    # Otherwise, use the weighted average.
    combined_score = (model_score * 0.70) + (style_score * 0.30)

    return combined_score



def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a combined score into a machine-readable guess
        and the sentence shown to the writer.

    Returns:
        (guess, label_text) — where `guess` is a short machine-readable string
        like "ai" / "human" / "unsure", and `label_text` is the full sentence
        shown to a person.
    """

    if score >= config.AI_THRESHOLD:
        return "ai", "We think this was probably written by AI."

    if score <= config.HUMAN_THRESHOLD:
        return "human", "We think this was probably written by a person."

    return "unsure", "We can't confidently tell whether this was written by a person or by AI."


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
